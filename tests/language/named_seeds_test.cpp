// clump.fork(3).fork(7) and clump.fork(7).fork(3) from base 7
constexpr u32 kChain37 = 0x613201b5u;
constexpr u32 kChain73 = 0x29acae70u;
constexpr u32 kTextTag = 0x80d7e5dcu, kIndexTag = 0x986d7397u;
constexpr u32 kLeavesSalt = 0x6ab9af40u;


// The 32 bits of every point of the first output, from two exact 16-bit halves.
std::vector<u32> seeds(const RunOutcome& run) {
    std::vector<u32> result;
    for (const auto& point : run.outputs.at(0).points)
        result.push_back((static_cast<u32>(point.x) << 16) | static_cast<u32>(point.y));
    return result;
}

[[maybe_unused]] std::vector<u32> seeds(const GenerationResult& result, const char* name) {
    std::vector<u32> values;
    const auto* output = result.find(name);
    REQUIRE(output != nullptr);
    for (const auto& point : output->points)
        values.push_back((static_cast<u32>(point.x) << 16) | static_cast<u32>(point.y));
    return values;
}

// Writes a seed into the list output `out` as two exact halves.
constexpr const char* kEmit = R"(
  emit(v: seed) { bits = int(v) out = {float((bits >> 16) & 0xffff), float(bits & 0xffff)} }
  emitBits(bits: i32) { out = {float((bits >> 16) & 0xffff), float(bits & 0xffff)} })";

std::string program(const std::string& body, const std::string& helpers = "") {
    return "asset named { size 4x4 output list point out\n draw {\n" + body + "\n }" + kEmit + helpers + "\n}";
}

GenerationResult runParts(const ips::Program& root, const std::map<std::string, const ips::Program*>& parts,
                          u32 seed, bool optimize = true) {
    std::map<std::string, ips::PartInfo> infos;
    for (const auto& [alias, part] : parts) infos.emplace(alias, ips::partInfoOf(part->asset));
    ips::checkAsset(root, infos);
    const auto bytes = compileProgram(root, parts, optimize);
    const auto loaded = loadFile(bytes);
    validate(loaded);
    VM vm(loaded, GenerationInputs{seed, 0, 0, {}});
    vm.run();
    return vm.result();
}

